RATING_STYLE = {"Good": "good", "Moderate": "moderate", "Low": "low", "Not tested": "unknown"}


def _n(x):
    """Whole number with thousands separators."""
    try:
        return f"{int(round(float(x))):,}"
    except Exception:
        return "—"


def _month(t):
    return pd.Timestamp(t).strftime("%B %Y")


def _glossary(items):
    return "<dl class='glossary'>" + "".join(
        f"<dt>{html.escape(k)}</dt><dd>{html.escape(v)}</dd>" for k, v in items) + "</dl>"


def _rating_badge(rating):
    return f"<span class='rating {RATING_STYLE.get(rating, 'unknown')}'>{html.escape(rating)}</span>"


