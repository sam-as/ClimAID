"""Plain-language layer for ClimAID v2 reports.

The technical C-DSI v2 interpretation is precise but written for modellers
(WIS, quantiles, hindcasts, coverage). This module turns the same numbers into
short, everyday sentences for health officers, planners and the public. Like
C-DSI it is fully deterministic: every sentence comes from fixed rules applied
to the run's own numbers; nothing is generated by an LLM.

Conventions used in all plain text
----------------------------------
- "Likely range" = the 80% interval: in 8 out of 10 cases the real number
  should fall inside it.
- "Typical year" = the average for the same calendar month over the last (up
  to) five years before the forecast start, leaving out replaced months.
- Numbers are rounded to whole cases; percentages to whole numbers.
"""
from __future__ import annotations

import html
import numpy as np
import pandas as pd

