def scenario_trust(outlook, sensitivity=None, backtest=None):
    """Good / Moderate / Low confidence in the scenario projections, with reasons.

    One point each for: (1) the backtest on held-out years was not worse than
    repeating the historical average; (2) the climate models agree on the
    direction of change (>= 80% of outcomes the same way in the last decade);
    (3) results are not highly sensitive to how climate effects are learned
    (<= 10 percentage points); (4) the data could pin down which climate factors
    matter (at most 2 near-equally-good explanations). 4 = Good, 2-3 = Moderate,
    0-1 = Low.
    """
    reasons, points = [], 0
    dec, meta = outlook.decades, outlook.metadata
    if backtest and backtest.get("summary") and "median_abs_pct_error" in backtest["summary"]:
        sm = backtest["summary"]
        e, e0 = sm["median_abs_pct_error"], sm["median_abs_pct_error_training_mean"]
        if e <= 1.2 * e0:
            points += 1
            reasons.append(f"When we tested the method on {sm['n_years']} past years it had not seen, it was about as accurate as "
                           f"or better than simply using the historical average (typical error {e:.0%}).")
        else:
            reasons.append(f"When tested on {sm['n_years']} past years it had not seen, it was less accurate than simply using the historical average.")
    else:
        reasons.append("The method could not be tested on past years.")
    if not dec.empty:
        last = sorted(dec["decade"].unique())[-1]
        shares = dec[dec.decade == last]["share_gcm_samples_increase"]
        agree = shares.map(lambda x: max(x, 1 - x)).min()
        if agree >= 0.8:
            points += 1
            reasons.append("The climate models mostly agree on whether cases go up or down.")
        else:
            reasons.append("The climate models do not agree on whether cases will go up or down.")
    if sensitivity is not None and not dec.empty and not sensitivity.decades.empty:
        last = sorted(dec["decade"].unique())[-1]
        a = dec[dec.decade == last].set_index("ssp").change_vs_baseline_median
        b = sensitivity.decades[sensitivity.decades.decade == last].set_index("ssp").change_vs_baseline_median
        gap = (a - b).abs().max()
        if np.isfinite(gap) and gap <= 0.10:
            points += 1
            reasons.append("The results hold up when we change how the effect of climate is estimated.")
        else:
            reasons.append(f"The results change noticeably (by up to {gap * 100:.0f} percentage points) depending on how the effect of climate is estimated.")
    n_struct = len(meta.get("lag_structures") or [])
    if n_struct <= 2:
        points += 1
    else:
        reasons.append(f"The past data fit {n_struct} different explanations about equally well (for example, whether heat or rain matters more). "
                       "They predict different amounts of change, so the likely range is wide.")
    rating = "Good" if points >= 4 else ("Moderate" if points >= 2 else "Low")
    return rating, reasons


def plain_scenario_html(outlook, *, disease_name, district, sensitivity=None, backtest=None):
    dec, base, meta = outlook.decades, outlook.baseline, outlook.metadata
    place = html.escape(_district_name(district)); dis = html.escape(disease_name)
    bullets = []
    if not dec.empty:
        decades = sorted(dec["decade"].unique())
        last = decades[-1]
        for s in meta["ssps"]:
            r = dec[(dec.ssp == s) & (dec.decade == last)]
            if r.empty:
                continue
            r = r.iloc[0]
            ch, lo, hi = r.change_vs_baseline_median, r.change_p10, r.change_p90
            more = r.annual_median - base["model_annual_mean"]
            dirw = "more" if ch >= 0 else "fewer"
            bullets.append(
                f"<strong>{html.escape(SSP_PLAIN.get(s, s.upper()))}:</strong> by the <strong>{last}</strong>, about "
                f"<strong>{_n(r.annual_median)} cases a year</strong> — roughly {abs(ch) * 100:.0f}% {dirw} than in "
                f"{base['years']} ({_n(abs(more))} {dirw} cases a year). "
                f"Likely range: {_range_words(lo, hi)}.")
        if len(meta["ssps"]) > 1:
            bullets.append(_pathway_comparison(dec, decades))
    rating, reasons = scenario_trust(outlook, sensitivity, backtest)
    bullets.append(f"Confidence in these projections: {_rating_badge(rating)} — see below.")
    summary = (f"<p class='lede'>What could happen to {dis} in {place} as the climate changes, if everything else "
               f"(population, mosquito control, testing) stayed the same as in {base['years']}.</p>"
               "<ul class='summary'>" + "".join(f"<li>{b}</li>" for b in bullets) + "</ul>")
    trust = (f"<p class='rating-line'>{_rating_badge(rating)}</p><ul>" +
             "".join(f"<li>{html.escape(x)}</li>" for x in reasons) + "</ul>" +
             "<p class='muted'>How the rating is worked out: one point each for (1) doing at least as well as the historical "
             "average on past years it had not seen, (2) the climate models agreeing on the direction of change, (3) results "
             "holding up under a different way of estimating climate effects, and (4) the data pointing to a clear "
             "explanation. 4 points = Good, 2–3 = Moderate, 0–1 = Low.</p>")
    not_incl = ["Changes in population. " + ("A separate table in the technical details shows results with projected population." if getattr(outlook, "decades_with_population", None) is not None else "More people usually means more cases."),
                "Changes in mosquito control, housing, water storage, testing or reporting.",
                "New virus strains or changes in immunity.",
                "Extreme events such as floods, which can cause outbreaks the monthly averages do not capture."]
    notes = "<ul>" + "".join(f"<li>{html.escape(x)}</li>" for x in not_incl) + "</ul>"
    return summary, trust, notes, _glossary(GLOSSARY_SCENARIO)


def _pathway_comparison(dec, decades):
    """Compare emissions pathways from the numbers, never by assumption."""
    first, last = decades[0], decades[-1]
    # use the same rounded percentages the reader sees, so the stated gap matches
    g = lambda d: (dec[dec.decade == d].change_vs_baseline_median * 100).round()
    gap0, gap1 = float(g(first).max() - g(first).min()) / 100, float(g(last).max() - g(last).min()) / 100
    rows = dec[dec.decade == last]
    overlap = rows.change_p10.max() <= rows.change_p90.min()
    if gap1 >= 0.05 and gap1 - gap0 >= 0.05:
        txt = (f"The gap between the pathways grows over time: about {gap0 * 100:.0f} percentage points in the {first}, "
               f"about {gap1 * 100:.0f} by the {last}. What the world does about emissions matters more further ahead.")
        if overlap:
            txt += " Their likely ranges overlap, so the difference is not certain."
    else:
        txt = (f"The pathways give similar results (within about {gap1 * 100:.0f} percentage points by the {last}), "
               f"so up to then the choice of pathway makes less difference than the other uncertainties.")
    return txt


def _range_words(lo, hi):
    def w(x):
        return f"{abs(x) * 100:.0f}% {'more' if x >= 0 else 'fewer'}"
    if lo >= 0 or hi <= 0:
        return f"from {w(lo)} to {w(hi)}"
    return f"from {w(lo)} to {w(hi)} — so a decrease cannot be ruled out"


def partner_logo_html():
    """NDMC logo on a white badge for the dark report header (embedded, so reports stay self-contained)."""
    import base64
    from pathlib import Path
    path = Path(__file__).parent / "assets" / "ndmc_logo.png"
    if not path.exists():
        return ""
    b64 = base64.b64encode(path.read_bytes()).decode()
    return ("<div class='partner-badge'><img src='data:image/png;base64," + b64 +
            "' alt='National Disease Modelling Consortium (NDMC)'></div>")


